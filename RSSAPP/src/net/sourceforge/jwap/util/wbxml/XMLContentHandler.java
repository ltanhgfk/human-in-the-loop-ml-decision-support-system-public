	public void startPrefixMapping(String prefix, String uri) throws SAXException {
		//System.out.println("startPrefixMapping" + prefix + uri);
		String urnString = uri;
		TokenRepository.switchCodepage(urnString.toLowerCase());
		switchCodepage = true;
		Token switchCodePageToken = new Token("SWITCH_CODEPAGE", (byte)0);
		tokens.addElement(switchCodePageToken);
		Token codePageToken = new Token("CODEPAGENO", TokenRepository.getCurrentCodepage());
		tokens.addElement(codePageToken);
		super.startPrefixMapping(prefix, uri);
	}

