	/**
	 * @see org.xml.sax.ContentHandler#startElement(String, String, String, Attributes)
	 */
	public void startElement(String namespaceURI, String localName, String qName, Attributes atts) throws SAXException {
	//	System.out.println("startElement" + qName);
		if (!publicIdTokenAdded) {// The document does not have Doctype Declaration which means Public ID 1 (for "UNKNOWN") should be addded 
			Token publicIdToken = new Token("publicid",(byte)1);
			tokens.addElement(publicIdToken);
			tokenRepository = TokenRepository.getInstance("1");
			publicIdTokenAdded = true;
		}  
		checkForParentTag();
		boolean hasAttributes = atts.getLength() > 0;
		createTagToken(localName, hasAttributes);
		if (hasAttributes)
			createAttributeTags(localName, atts);
	}

	private void checkForParentTag() {
		// check if this element has a parent..
		if (!parentTrace.isEmpty()) {
			TagToken parentToken = (TagToken) parentTrace.pop();
			if (parentToken != null) { // apply the bit mask for parent tag.
				byte tokenValue = (byte) (parentToken.getValue() | parentBitMask);
				parentToken.setValue(tokenValue);
			}
		}
	}

	private void createTagToken(String elementName, boolean hasAttributes) {
		// create token for current element
		byte tokenValue = tokenRepository.getTagToken(elementName);
		TagToken currentTagToken = new TagToken(elementName, tokenValue);
		// store on tokenArray
		tokens.addElement(currentTagToken);
		// push the current token on stack
		parentTrace.push(currentTagToken);

		// apply bit mask for tag with attributes
		if (hasAttributes) {
			byte currentTokenValue = (byte) (currentTagToken.getValue() | attributeBitMask);
			currentTagToken.setValue(currentTokenValue);
		}

	}

	private void createAttributeTags(String localName, Attributes atts) {
		// process attributes name and prefix..
		for (int i = 0; i < atts.getLength(); i++) {
		//	System.out.println("&&" +atts.getURI(i));
			if (atts.getURI(i).length() <= 0) {
				String attributeName = atts.getLocalName(i);
				String attributeValue = atts.getValue(i);
				String prefix = getAttributePrefix(attributeName, attributeValue);
				byte attributeTokenValue = tokenRepository.getAttributeNameToken(attributeName, prefix);
				AttributeNameToken attrNameToken = new AttributeNameToken(attributeName, attributeTokenValue);
				// store on tokens vector
				tokens.addElement(attrNameToken);
				// do the same for remaining attribute value ....
				String remainingAttrValue = attributeValue.substring(prefix.length()).trim();
				if (remainingAttrValue.length() > 0)
					processAttributeValue(remainingAttrValue);
			}

		}
		tokens.addElement(new TagToken("END attribute" + localName, GlobalTokens.END));
	}

	private String getAttributePrefix(String attributeName, String attributeValue) {
		Vector prefixes = tokenRepository.getAttributePrefixes(attributeName);
		if(prefixes == null) return "";
		Iterator iterator = prefixes.iterator();
		int maxMatchSize = 0;
		String maxMatchedPrefix = "";
		while (iterator.hasNext()) {
			String prefix = (String) iterator.next();
			if (attributeValue.startsWith(prefix) && maxMatchSize < prefix.length()) {
				maxMatchedPrefix = prefix;
				maxMatchSize = prefix.length();
			}
		}
		return maxMatchedPrefix;
	}

	private void processAttributeValue(String attributeValue) {
		String maxMatchedValue = getMatchedPattern(attributeValue);
		if (maxMatchedValue.length() == 0) {
			writeInlineString(attributeValue);
			return;
		}
		int matchStartIdx = maxMatchedValue.length() > 0 ? attributeValue.indexOf(maxMatchedValue) : 0;
		int matchEndIdx = matchStartIdx + maxMatchedValue.length();
		if (matchStartIdx != 0) {
			String startOfAttrValue = attributeValue.substring(0, matchStartIdx);
			writeInlineString(startOfAttrValue);
		}
		byte tokenValue = tokenRepository.getAttributeValueToken(maxMatchedValue);
		AttributeValueToken token = new AttributeValueToken("attvalue", tokenValue);
		tokens.addElement(token);
		if (matchEndIdx != 0) {
			String endOfAttrValue = attributeValue.substring(matchEndIdx);
			writeInlineString(endOfAttrValue);
		}

	}

	private String getMatchedPattern(String attributeValue) {
		String maxMatchedValue = "";
		int maxMatchSize = 0;
		Enumeration enum1 = tokenRepository.getAttributeValues().keys();
		while (enum1.hasMoreElements()) {
			String predefinedValue = (String) enum1.nextElement();
			boolean exists = attributeValue.indexOf(predefinedValue) != -1 ? true : false;
			if (exists && maxMatchSize < predefinedValue.length()) {
				maxMatchedValue = predefinedValue;
				maxMatchSize = predefinedValue.length();
			}
		}
		return maxMatchedValue.trim();
	}

	private void writeInlineString(String inlineString) {
		writeInlineStringToken(GlobalTokens.STR_ISTR_I);
		for (int j = 0; j < inlineString.length(); j++)
			writeInlineStringToken((byte) inlineString.charAt(j));
		writeInlineStringToken((byte) 00);

	}

	private void writeInlineStringToken(byte value) {
		Token stringToken = new Token("STR_INLINE", value);
		tokens.addElement(stringToken);
	}

